package ui

import (
	"fmt"
	"maps"
	"slices"

	"github.com/manifoldco/promptui"
)

func SelectPod(pods map[string]int32, label string) (string, int32, error) {
	prompt := promptui.Select{
		Label: label,
		Items: slices.Collect(maps.Keys(pods)),
	}

	_, name, err := prompt.Run()
	if err != nil {
		return "", 0, err
	}
	return name, pods[name], nil
}

